// Helper to generate seat layouts
export function generateBusSeats(busType: 'Sleeper' | 'Seater' | 'Semi-Sleeper'): Seat[] {
  const seats: Seat[] = [];
  const basePrice = busType === 'Sleeper' ? 1250 : busType === 'Semi-Sleeper' ? 850 : 650;

  if (busType === 'Sleeper') {
    // 2 decks: Lower Deck (15 berths) + Upper Deck (15 berths) -> 30 seats total
    // Layout 2+1: Left row (columns 1, 2), Gangway, Right row (column 3)
    const decks: Array<'lower' | 'upper'> = ['lower', 'upper'];
    decks.forEach((deck) => {
      const prefix = deck === 'lower' ? 'L' : 'U';
      for (let r = 1; r <= 5; r++) {
        // Left side (2 berths)
        seats.push({
          id: `${prefix}${r}A`,
          number: `${prefix}${r}A`,
          row: r,
          column: 1,
          deck,
          type: 'sleeper',
          price: deck === 'lower' ? basePrice : basePrice - 50,
          status: (r === 2 && prefix === 'L') ? 'female_reserved' : (r === 1 || r === 4) ? 'occupied' : 'available',
        });
        seats.push({
          id: `${prefix}${r}B`,
          number: `${prefix}${r}B`,
          row: r,
          column: 2,
          deck,
          type: 'sleeper',
          price: deck === 'lower' ? basePrice : basePrice - 50,
          status: (r === 3 && prefix === 'U') ? 'occupied' : 'available',
        });
        // Right side (single berth)
        seats.push({
          id: `${prefix}${r}C`,
          number: `${prefix}${r}C`,
          row: r,
          column: 3,
          deck,
          type: 'sleeper',
          price: deck === 'lower' ? basePrice + 100 : basePrice + 50,
          status: (r === 2 && prefix === 'U') ? 'male_reserved' : (r === 5) ? 'occupied' : 'available',
        });
      }
    });
  } else {
    // 2+2 Seater layout (36 seats total)
    for (let r = 1; r <= 9; r++) {
      ['A', 'B', 'C', 'D'].forEach((colLetter, idx) => {
        const seatNum = `${r}${colLetter}`;
        const isOccupied = (r === 1 && idx === 1) || (r === 3 && idx === 0) || (r === 4 && idx === 3) || (r === 7 && idx === 2);
        const isFemale = (r === 2 && idx === 0);
        seats.push({
          id: seatNum,
          number: seatNum,
          row: r,
          column: idx + 1,
          deck: 'lower',
          type: busType === 'Semi-Sleeper' ? 'semi-sleeper' : 'seater',
          price: r <= 2 ? basePrice + 100 : basePrice,
          status: isOccupied ? 'occupied' : isFemale ? 'female_reserved' : 'available',
        });
      });
    }
  }

  return seats;
}

